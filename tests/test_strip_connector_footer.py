import subprocess
import sys
import unittest
from pathlib import Path

SCRIPT = Path(__file__).resolve().parent.parent / ".github" / "scripts" / "strip_connector_footer.py"
FOOTER = "_Generated by [Claude Code](https://claude.ai/code/session_011Ang7B6MBCKcAzHiMPAy3t)_"


def strip(body):
    return subprocess.run(
        [sys.executable, SCRIPT], input=body.encode(), capture_output=True, check=True
    ).stdout.decode()


class StripConnectorFooter(unittest.TestCase):
    def test_removes_footer(self):
        for body in [
            f"Fixes #1.\n\nadds tests\n\n---\n{FOOTER}",
            f"Fixes #1.\n\nadds tests\n\n---\n{FOOTER}\n",
            f"Fixes #1.\n\nadds tests\n\n{FOOTER}",
        ]:
            with self.subTest(body=body):
                self.assertEqual(strip(body), "Fixes #1.\n\nadds tests")
        # Bodies edited on github.com come back with CRLF line endings.
        self.assertEqual(strip(f"a\r\nb\r\n\r\n---\r\n{FOOTER}"), "a\r\nb")

    def test_leaves_everything_else(self):
        for body in [
            "Fixes #1.\n\nadds tests\n",
            "a\r\nb\r\n",
            "",
            f"{FOOTER}\n\nbut text follows",
            "notes\n\n---\n_Generated by [protoc](https://example.com)_",
        ]:
            with self.subTest(body=body):
                self.assertEqual(strip(body), body)


if __name__ == "__main__":
    unittest.main()
